import type { ConservationCode } from "../lib/conservation";

export interface BirdMorphometrics {
  massG: number;
  massFormatted: string;
  wingLengthMm: number;
  wingspanCm: string;
  beakLengthCulmenMm: number;
  beakWidthMm: number;
  beakDepthMm: number;
  tarsusLengthMm: number;
  tailLengthMm: number;
  handWingIndex: number; // Dispersal / flight aerodynamic efficiency index
  kippsDistanceMm: number;
}

export interface BirdEcology {
  habitat: string;
  habitatDensity: string; // "Dense habitats" | "Semi-open habitats" | "Open habitats"
  migrationLabel: string; // "Sedentary" | "Partially migratory" | "Migratory (long-distance)"
  trophicLevel: string; // "Carnivore" | "Herbivore" | "Omnivore"
  trophicNiche: string; // "Aquatic predator" | "Granivore" | "Invertivore" | "Nectarivore" | "Vertivore"
  primaryLifestyle: string; // "Insessorial" | "Terrestrial" | "Aerial" | "Aquatic"
  rangeSizeKm2: number;
  rangeSizeFormatted: string;
  ecosystems: {
    terrestrial: boolean;
    freshwater: boolean;
    marine: boolean;
  };
}

export interface BirdConservation {
  rlCategory: ConservationCode;
  rlLabel: string;
  populationTrend: "Stable" | "Decreasing" | "Increasing" | "Unknown";
  populationSize?: string;
  threatened: boolean;
}

export interface BirdTelemetry {
  hasTracking: boolean;
  points: number;
  individuals: number;
  studies: number;
  firstTimestamp?: string;
  lastTimestamp?: string;
  peakMonth?: string;
  topCountries?: string[];
  monthlyDistribution?: number[]; // 12 monthly normalized occurrences (GBIF / Movebank)
}

export interface BirdAudioTelemetry {
  hasAudio: boolean;
  recordingCount: number;
  primarySoundType: string;
  soundDescription: string;
  recordist?: string;
}

export interface BirdSpecies {
  id: string;
  name: string; // Display nickname / main title
  commonName: string; // Standard English name
  scientificName: string;
  family: string;
  order: string;
  sublabel: string;
  iucnCategory: ConservationCode;
  iucnLabel: string;
  imageUrl: string;
  thumbnailUrl?: string;
  description: string;
  habitat: string;
  diet: string;
  lengthCm: string;
  wingspanCm: string;
  massG: string;
  range: string;
  tags: string[];
  has3dModel?: boolean;
  featured?: boolean;
  soundDescription?: string;

  // Joined backend-mirroring schemas (AVONET, Movebank, BirdLife, GBIF, Xeno-canto)
  morphometrics: BirdMorphometrics;
  ecology: BirdEcology;
  conservation: BirdConservation;
  telemetry: BirdTelemetry;
  audio: BirdAudioTelemetry;
}

